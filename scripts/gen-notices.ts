// Writes THIRD_PARTY_NOTICES.md with the licenses of code shipped in the container image
// (server dependencies) and in the browser bundle.
//
//   node scripts/gen-notices.ts

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const groups: Array<[string, string[]]> = [
  ['Server (container image)', ['ws', 'yaml', 'zod']],
  ['Browser bundle', ['three', 'iwer', 'gl-matrix', 'webxr-layers-polyfill']],
];

const out = [
  '# Third-party notices',
  '',
  'web-colocation includes the following third-party software. Generated by `node scripts/gen-notices.ts`.',
  '',
];
for (const [title, packages] of groups) {
  out.push(`## ${title}`, '');
  for (const name of packages) {
    const dir = join(root, 'node_modules', name);
    const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')) as { version: string; license?: string; repository?: string | { url: string }; homepage?: string };
    const licenseFile = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f));
    const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
    out.push(`### ${name} ${pkg.version}`, '', `License: ${pkg.license ?? 'see below'}${repo ? ` — ${repo.replace(/^git\+/, '')}` : ''}`, '');
    if (licenseFile && existsSync(join(dir, licenseFile))) {
      out.push('```', readFileSync(join(dir, licenseFile), 'utf8').trim(), '```', '');
    }
  }
}
writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), out.join('\n'));
console.log('wrote THIRD_PARTY_NOTICES.md');
