// Generates docs/configuration-reference.md from the zod config schema.
//
//   npm run gen:docs

import { writeFileSync } from 'node:fs';
import { z } from 'zod';
import { AppConfigSchema } from '../server/config/schema.ts';

interface Schema {
  type?: string | string[];
  properties?: Record<string, Schema>;
  items?: Schema;
  anyOf?: Schema[];
  enum?: unknown[];
  const?: unknown;
  default?: unknown;
  description?: string;
  pattern?: string;
  format?: string;
  minimum?: number;
  maximum?: number;
  additionalProperties?: Schema | boolean;
  prefixItems?: Schema[];
}

const root = z.toJSONSchema(AppConfigSchema, { io: 'input', target: 'draft-2020-12' }) as Schema;

function typeOf(s: Schema): string {
  if (s.enum) return s.enum.map((v) => `\`${JSON.stringify(v)}\``).join(' \\| ');
  if (s.const !== undefined) return `\`${JSON.stringify(s.const)}\``;
  if (s.anyOf) return s.anyOf.map(typeOf).join(' \\| ');
  if (s.prefixItems) return `[${s.prefixItems.map(typeOf).join(', ')}]`;
  if (s.type === 'array') return `${s.items ? typeOf(s.items) : 'any'}[]`;
  if (s.type === 'object' && s.additionalProperties && typeof s.additionalProperties === 'object') return 'map';
  if (s.type === 'integer') return 'integer';
  return Array.isArray(s.type) ? s.type.join(' \\| ') : (s.type ?? 'any');
}

function range(s: Schema): string {
  const parts: string[] = [];
  if (s.minimum !== undefined) parts.push(`≥ ${s.minimum}`);
  if (s.maximum !== undefined) parts.push(`≤ ${s.maximum}`);
  if (s.format) parts.push(s.format);
  return parts.length ? ` (${parts.join(', ')})` : '';
}

const fmtDefault = (v: unknown) => (v === undefined ? '' : `\`${JSON.stringify(v)}\``);
const esc = (t: string | undefined) => (t ?? '').replaceAll('|', '\\|').replaceAll('\n', ' ');

const sections: Array<{ title: string; rows: string[] }> = [];

function walk(s: Schema, path: string, section: { title: string; rows: string[] }): void {
  for (const [key, prop] of Object.entries(s.properties ?? {})) {
    const p = path ? `${path}.${key}` : key;
    const isObject = prop.type === 'object' && prop.properties;
    const arrayOfObjects = prop.type === 'array' && prop.items?.type === 'object' && prop.items.properties;
    if (isObject) {
      walk(prop, p, section);
      continue;
    }
    section.rows.push(`| \`${p}\` | ${typeOf(prop)}${range(prop)} | ${fmtDefault(prop.default)} | ${esc(prop.description)} |`);
    if (arrayOfObjects) {
      const sub = { title: `\`${p}[]\``, rows: [] as string[] };
      sections.push(sub);
      walk(prop.items!, '', sub);
    }
  }
}

for (const [key, prop] of Object.entries(root.properties ?? {})) {
  const section = { title: `\`${key}\``, rows: [] as string[] };
  sections.push(section);
  if (prop.type === 'object' && prop.properties) walk(prop, key, section);
  else {
    section.rows.push(`| \`${key}\` | ${typeOf(prop)} | ${fmtDefault(prop.default)} | ${esc(prop.description)} |`);
    if (prop.type === 'array' && prop.items?.properties) {
      const sub = { title: `\`${key}[]\``, rows: [] as string[] };
      sections.push(sub);
      walk(prop.items, '', sub);
    }
  }
}

const out = [
  '<!-- Generated by `npm run gen:docs` from server/config/schema.ts — do not edit by hand. -->',
  '',
  '# Configuration reference',
  '',
  'All options of the configuration file (`COLO_CONFIG`, or `config:` in the Helm chart).',
  'Units are meters and degrees. See [configuration.md](configuration.md) for a guided tour and',
  '[room-templates.md](room-templates.md) for layouts. Editors that support',
  '`# yaml-language-server: $schema=...` can validate and autocomplete with',
  '[`schema/config.schema.json`](../schema/config.schema.json).',
  '',
];
for (const s of sections) {
  if (!s.rows.length) continue;
  out.push(`## ${s.title}`, '', '| Option | Type | Default | Description |', '|---|---|---|---|', ...s.rows, '');
}
const file = new URL('../docs/configuration-reference.md', import.meta.url);
writeFileSync(file, out.join('\n'));
console.log(`wrote docs/configuration-reference.md (${sections.length} sections)`);
